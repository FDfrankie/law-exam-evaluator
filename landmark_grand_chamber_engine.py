def get_grand_chamber_ruling(case_id_or_keyword: str) -> Optional[Dict[str, Any]]:
    """根據字號或關鍵字檢索權威大法庭裁定全文與理由"""
    if not case_id_or_keyword:
        return None
    clean = case_id_or_keyword.strip()
    for k, v in LANDMARK_GRAND_CHAMBER_DATABASE.items():
        if k in clean or clean in v["case_id"] or k.replace("年度", "").replace("字第", "") in clean:
            return v
    # 搜尋數字如 1636
    for k, v in LANDMARK_GRAND_CHAMBER_DATABASE.items():
        case_num = "".join(filter(str.isdigit, k))
        if case_num and case_num in clean and ("台上大" in clean or "大法庭" in clean or "判例" in clean):
            return v
    return None

def get_grand_chamber_full_text(case_id_or_keyword: str) -> str:
    """取得大法庭官方完整裁判全文（附理由書）"""
    doc = get_grand_chamber_ruling(case_id_or_keyword)
    if doc:
        return doc.get("full_text", "")
    return ""

def get_grand_chamber_holding(case_id_or_keyword: str) -> str:
    """取得大法庭主文與核心要旨"""
    doc = get_grand_chamber_ruling(case_id_or_keyword)
    if doc:
        return doc.get("holding", "")
    return ""
