def get_taxonomy_chapters_for_subject(subject_name: str) -> List[str]:
    """
    根據使用者選取的科目名稱，智慧過濾出所屬的體系章節分類清單
    若選「全部科目」或跨學門，則回傳全 16 大體系章節
    """
    all_chapters = list(MASTER_CURATED_ISSUES.keys())
    if not subject_name or "全部科目" in subject_name or "跨學門" in subject_name:
        return ["🌟 全部體系章節大庫 (跨領域綜合檢索)"] + all_chapters

    # 科目專屬匹配過濾
    matched = []
    for chap in all_chapters:
        if any(w in chap for w in [subject_name[:2], subject_name[:4]] if len(w) >= 2):
            matched.append(chap)
        elif "民法" in subject_name and "民法" in chap:
            matched.append(chap)
        elif "民訴" in subject_name and "民事訴訟" in chap:
            matched.append(chap)
        elif "刑法" in subject_name and "刑法" in chap:
            matched.append(chap)
        elif "刑訴" in subject_name and "刑事訴訟" in chap:
            matched.append(chap)
        elif "行政" in subject_name and "行政法" in chap:
            matched.append(chap)
        elif "憲法" in subject_name and "憲法" in chap:
            matched.append(chap)
        elif "商事" in subject_name and "商事法" in chap:
            matched.append(chap)
        elif any(k in subject_name for k in ["公司", "證券", "保險", "票據"]) and "商事法" in chap:
            matched.append(chap)
        elif any(k in subject_name for k in ["家事", "強執"]) and "家事" in chap:
            matched.append(chap)
        elif any(k in subject_name for k in ["智財", "勞動"]) and "智慧財產" in chap:
            matched.append(chap)

    if not matched:
        return ["🌟 全部體系章節大庫 (跨領域綜合檢索)"] + all_chapters

    return matched

def get_curated_issues_by_chapter(chapter_name: str, subject_name: str = "") -> Dict[str, Dict[str, str]]:
    """
    取得該章節下所有預先寫好的具體法學爭點
    若選擇「全部體系章節大庫」，則匯總傳回所有章節之爭點（逾 150+ 則）
    """
    if "全部體系章節" in chapter_name or not chapter_name:
        result = {}
        # 如果有特定科目，先抓該科目對應之所有章節
        target_chapters = get_taxonomy_chapters_for_subject(subject_name)
        if target_chapters and target_chapters[0].startswith("🌟"):
            target_chapters = target_chapters[1:]

        for ch in target_chapters:
            if ch in MASTER_CURATED_ISSUES:
                result.update(MASTER_CURATED_ISSUES[ch])
        return result

    return MASTER_CURATED_ISSUES.get(chapter_name, {})

def get_total_curated_issues_count() -> int:
    """傳回全庫預寫爭點總數"""
    return sum(len(issues) for issues in MASTER_CURATED_ISSUES.values())

